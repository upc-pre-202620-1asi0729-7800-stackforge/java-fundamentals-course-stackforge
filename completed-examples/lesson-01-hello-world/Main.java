// Un programa es una lista de instrucciones que la computadora sigue en orden.

public class Main {
    public static void main(String[] args) {
        // System.out.println muestra un mensaje en la consola y salta de línea
        System.out.println("¡Hola, mundo!");
        System.out.println("Estoy escribiendo mi primer programa en Java.");

        // Las instrucciones se ejecutan de arriba hacia abajo
        System.out.println("Paso 1: despertar");
        System.out.println("Paso 2: desayunar");
        System.out.println("Paso 3: ¡aprender Java!");
    }
}
